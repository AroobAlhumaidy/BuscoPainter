#!/usr/bin/env python3
"""Generate the synthetic BuscoPainter example in examples/data/.

Everything here is invented: random DNA with hand-placed open reading frames, and a BUSCO-like
run directory (full_table.tsv, short_summary.json, per-BUSCO miniprot-style GFFs) that mimics the
BUSCO v6 / miniprot layout. It is NOT real BUSCO output and has no biological meaning.

The output is deterministic (fixed random seeds). Re-running it overwrites examples/data/.

    python examples/make_example_data.py
"""
import json
import random
from pathlib import Path

from Bio.Seq import Seq

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
LINEAGE = "example_odb12"
STATUS_DIRS = {"Complete": "single_copy_busco_sequences",
               "Duplicated": "multi_copy_busco_sequences",
               "Fragmented": "fragmented_busco_sequences"}
SENSE = [a + b + c for a in "ACGT" for b in "ACGT" for c in "ACGT" if a + b + c not in ("TAA", "TAG", "TGA")]


def orf(n_codons, seed):
    """ATG + n random sense codons + TAA."""
    rnd = random.Random(seed)
    return "ATG" + "".join(rnd.choice(SENSE) for _ in range(n_codons)) + "TAA"


def rc(s):
    return str(Seq(s).reverse_complement())


class Builder:
    def __init__(self):
        rnd = random.Random(2026)
        self.contigs = {"contig_1": [rnd.choice("ACGT") for _ in range(6000)],
                        "contig_2": [rnd.choice("ACGT") for _ in range(2500)],
                        "contig_3": [rnd.choice("ACGT") for _ in range(800)]}  # no BUSCO hits
        self.rows = []      # full_table rows (strings)
        self.gff = {}       # (status, busco_id) -> GFF lines
        self.n = 0

    def place(self, contig, start1, seq):
        self.contigs[contig][start1 - 1:start1 - 1 + len(seq)] = list(seq)

    def hit(self, busco_id, status, contig, strand, cds, has_stop, attrs="", score=500.0):
        """cds: [(start, end, phase)] 1-based inclusive, as miniprot writes them.
        Adds the GFF model and the matching full_table row (BUSCO coordinate convention:
        0-based lower bound, stop codon excluded, written in strand order)."""
        self.n += 1
        mid = f"MP{self.n:06d}"
        lo, hi = min(c[0] for c in cds), max(c[1] for c in cds)
        a = f"ID={mid};Rank=1;Identity=0.9000;Positive=0.9500;Target={busco_id}_0:000{self.n:03d} 1 99"
        if attrs:
            a += f";{attrs}"
        lines = [f"{contig}\tminiprot\tmRNA\t{lo}\t{hi}\t1000\t{strand}\t.\t{a}"]
        for s, e, ph in cds:
            lines.append(f"{contig}\tminiprot\tCDS\t{s}\t{e}\t1000\t{strand}\t{ph}\t"
                         f"Parent={mid};Rank=1;Identity=0.9000;Target={busco_id}_0:000{self.n:03d} 1 99")
        if has_stop:
            st = (hi - 2, hi) if strand == "+" else (lo, lo + 2)
            lines.append(f"{contig}\tminiprot\tstop_codon\t{st[0]}\t{st[1]}\t0\t{strand}\t0\tParent={mid};Rank=1")
        self.gff.setdefault((status, busco_id), []).extend(lines)
        if strand == "+":
            ft_lo, ft_hi = lo - 1, hi - (3 if has_stop else 0)
            a_, b_ = ft_lo, ft_hi
        else:
            ft_lo, ft_hi = lo - 1 + (3 if has_stop else 0), hi
            a_, b_ = ft_hi, ft_lo
        n = (sum(e - s + 1 for s, e, _ in cds)) // 3
        self.rows.append(f"{busco_id}\t{status}\t{contig}\t{a_}\t{b_}\t{strand}\t{score}\t{n}\t"
                         f"https://example.invalid/?query={busco_id}\tsynthetic example protein {busco_id}")

    def missing(self, busco_id):
        self.rows.append(f"{busco_id}\tMissing")

    def write(self):
        DATA.mkdir(parents=True, exist_ok=True)
        with open(DATA / "genome.fasta", "w") as fh:
            for cid, s in self.contigs.items():
                seq = "".join(s)
                fh.write(f">{cid}\n" + "\n".join(seq[i:i + 60] for i in range(0, len(seq), 60)) + "\n")
        run = DATA / "busco" / f"run_{LINEAGE}"
        for sdir in STATUS_DIRS.values():
            (run / "busco_sequences" / sdir).mkdir(parents=True, exist_ok=True)
        for (status, bid), lines in self.gff.items():
            (run / "busco_sequences" / STATUS_DIRS[status] / f"{bid}.gff").write_text("\n".join(lines) + "\n")
        ids = {}
        for r in self.rows:
            bid, st = r.split("\t")[:2]
            ids.setdefault(st, set()).add(bid)
        n = len({r.split("\t")[0] for r in self.rows})
        hdr = ("# BUSCO version is: 6.0.0 \n"
               f"# The lineage dataset is: {LINEAGE} (SYNTHETIC EXAMPLE generated by make_example_data.py, "
               f"number of BUSCOs: {n})\n"
               "# Busco id\tStatus\tSequence\tGene Start\tGene End\tStrand\tScore\tLength\tOrthoDB url\tDescription\n")
        (run / "full_table.tsv").write_text(hdr + "\n".join(self.rows) + "\n")
        S, D, F, M = (len(ids.get(k, ())) for k in ("Complete", "Duplicated", "Fragmented", "Missing"))
        summary = {
            "note": "SYNTHETIC EXAMPLE generated by make_example_data.py; not produced by BUSCO",
            "lineage_dataset": {"name": LINEAGE, "number_of_buscos": str(n)},
            "versions": {"busco": "6.0.0", "miniprot_align": "synthetic"},
            "results": {"Complete BUSCOs": S + D, "Single copy BUSCOs": S, "Multi copy BUSCOs": D,
                        "Fragmented BUSCOs": F, "Missing BUSCOs": M, "n_markers": n},
        }
        (run / "short_summary.json").write_text(json.dumps(summary, indent=4) + "\n")


def main():
    b = Builder()
    b.missing("ex9at0")                        # a 2-field Missing row before any located row

    # ex1: + strand, one CDS segment, phase 0, with stop codon
    g = orf(60, 1)
    b.place("contig_1", 201, g)
    b.hit("ex1at0", "Complete", "contig_1", "+", [(201, 200 + len(g), 0)], True)

    # ex2: - strand, two CDS segments (frame-consistent), with stop codon. Flagged MULTI_SEGMENT_MODEL.
    g = orf(80, 2)                             # 246 nt; segment 1 = first 50 nt, segment 2 = 196 nt
    s1, s2 = g[:50], g[50:]
    b.place("contig_1", 801, rc(s2) + "A" * 40 + rc(s1))   # seg2 801..996, gap 997..1036, seg1 1037..1086
    b.hit("ex2at0", "Complete", "contig_1", "-", [(1037, 1086, 0), (801, 996, 1)], True)

    # ex3: + strand, GFF phase 1 (one extra leading base) -> /codon_start=2, boundaries NOT moved
    g = "C" + orf(40, 3)
    b.place("contig_1", 1501, g)
    b.hit("ex3at0", "Complete", "contig_1", "+", [(1501, 1500 + len(g), 1)], True)

    # ex4: Duplicated, three copies: two on contig_1 (+), one on contig_2 (-)
    g = orf(45, 4)
    b.place("contig_1", 2201, g)
    b.place("contig_1", 2801, g)
    b.place("contig_2", 301, rc(g))
    for s in (2201, 2801):
        b.hit("ex4at0", "Duplicated", "contig_1", "+", [(s, s + len(g) - 1, 0)], True)
    b.hit("ex4at0", "Duplicated", "contig_2", "-", [(301, 300 + len(g), 0)], True)

    # ex5: Fragmented, + strand, no stop codon
    g = orf(70, 5)[:150]
    b.place("contig_2", 1001, g)
    b.hit("ex5at0", "Fragmented", "contig_2", "+", [(1001, 1150, 0)], False, score=120.0)

    # ex6: miniprot reports a frameshift -> exported, translation omitted
    g = orf(50, 6)
    b.place("contig_1", 3601, g)
    b.hit("ex6at0", "Complete", "contig_1", "+", [(3601, 3600 + len(g), 0)], True, attrs="Frameshift=1")

    # ex7: two segments whose GFF phases are not one reading frame -> FRAME_INCONSISTENT, no translation
    g = orf(60, 7)                             # 186 nt; 40 + 146; true phase of segment 2 would be 2
    b.place("contig_1", 4201, g[:40])
    b.place("contig_1", 4401, g[40:])
    b.hit("ex7at0", "Complete", "contig_1", "+", [(4201, 4240, 0), (4401, 4400 + len(g) - 40, 0)], True)

    b.missing("ex8at0")
    b.write()
    print(f"Wrote synthetic example to {DATA}")


if __name__ == "__main__":
    main()
